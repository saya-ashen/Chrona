import { expect, test } from "@playwright/test";
import zh from "../packages/i18n/src/messages/zh.json" with { type: "json" };

test("question → research → result → revision → pause → settings", async ({ page, request }) => {
  const headers = { authorization: "Bearer steward-e2e-owner" };
  const scope = "workspaceId=ws_default";
  async function post(path: string, data: unknown = {}) {
    const response = await request.post(`/api/${path}?${scope}`, { headers, data });
    expect(response.ok(), `${path}: ${response.status()} ${await response.text()}`).toBe(true);
    return response.json();
  }
  await post("test/steward/reset");
  await post("test/steward/agent/install");
  await page.addInitScript(() => localStorage.setItem("chrona.accessKey", "steward-e2e-owner"));
  await page.goto("/zh");
  const composer = page.getByRole("textbox", { name: zh.steward.foundation.composer });
  await composer.fill("你好");
  await composer.press("Enter");
  await expect(page.getByText("收到", { exact: true })).toBeVisible();
  const affairs = await request.get(`/api/steward/affairs?${scope}`, { headers });
  expect((await affairs.json()).items).toEqual([]);
  await composer.fill("调研本地测试方案");
  await composer.press("Enter");
  await expect(page.getByText(/你.*调研本地测试方案/)).toBeVisible();
  await expect(composer).toBeEnabled();
  await page.getByRole("navigation", { name: zh.steward.shell.navigation }).getByRole("link", { name: "事务", exact: true }).click();
  await expect(page.getByRole("link", { name: "调研本地测试方案", exact: true })).toBeVisible();
  await post("test/steward/tick");
  await page.getByRole("navigation", { name: zh.steward.shell.navigation }).getByRole("link", { name: zh.steward.shell.today, exact: true }).click();
  await page.reload();
  const results = page.getByRole("region", { name: zh.steward.foundation.results });
  await expect(results.getByText("Test result v1 · v1")).toBeVisible();
  await results.getByRole("link", { name: zh.steward.foundation.read }).click();
  await expect(page.getByRole("table")).toBeVisible();
  const feedback = page.getByRole("textbox", { name: "修改意见", exact: true });
  await feedback.fill("补充比较依据");
  await page.locator("form").filter({ has: feedback }).getByRole("button", { name: "发送" }).click();
  await expect(feedback).toHaveValue("");
  await post("test/steward/tick");
  await page.reload();
  await page.getByRole("link", { name: `${zh.steward.affairs.version} 2`, exact: true }).click();
  await expect(page.getByRole("heading", { name: "Test result v2", exact: true }).first()).toBeVisible();
  await page.getByRole("link", { name: "← 调研本地测试方案" }).click();
  await page.getByRole("button", { name: "暂停", exact: true }).click();
  await expect(page.getByRole("button", { name: "继续", exact: true })).toBeVisible();
  await page.getByRole("navigation", { name: zh.steward.shell.navigation }).getByRole("link", { name: "事务", exact: true }).click();
  await expect(page.getByRole("region", { name: "已暂停" }).getByRole("link", { name: "调研本地测试方案" })).toBeVisible();
  await page.getByRole("navigation", { name: zh.steward.shell.navigation }).getByRole("link", { name: "设置", exact: true }).click();
  await page.getByRole("spinbutton", { name: zh.steward.settings.cap }).fill("7");
  await page.getByRole("button", { name: zh.steward.affairs.save, exact: true }).click();
  await expect(page.getByText(zh.steward.settings.saved, { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("spinbutton", { name: zh.steward.settings.cap })).toHaveValue("7");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
