import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

/** Compile-time shared application code; each release app receives its own private copy. */
export async function buildEntryConversations(resourcesRoot = resolve(import.meta.dir, "../packages/engine/src/modules/steward")) {
  const source = await readFile(resolve(import.meta.dir, "../packages/engine/src/modules/steward/entry-app/conversations.ts"), "utf8");
  const memory = await readFile(resolve(import.meta.dir, "../packages/engine/src/modules/steward/entry-app/memory.ts"), "utf8");
  const redaction = (await readFile(resolve(import.meta.dir, "../packages/logging/src/redaction.ts"), "utf8")).split("function isSensitiveKey")[0]!
    .replace(/^const (?:MAX_ARRAY_LENGTH|MAX_OBJECT_KEYS|SENSITIVE_KEY|SENSITIVE_CONTAINER_KEY) = .*;\n/gm, "");
  await writeFile(resolve(resourcesRoot, "external/memory-local/redaction.ts"), "// Generated by build/entry-conversations.ts from logging redaction.\n" + redaction.trimEnd() + "\n");
  for (const app of ["builtin/web", "external/mcp", "external/qq"]) {
    await writeFile(resolve(resourcesRoot, app, "agent-conversations.ts"), "// Generated by build/entry-conversations.ts from entry-app/conversations.ts.\n" + source);
    await writeFile(resolve(resourcesRoot, app, "memory.ts"), "// Generated by build/entry-conversations.ts from entry-app/memory.ts and logging redaction.\n" + memory.replace('import { redactSensitiveText } from "@chrona/logging/redaction";', redaction));
  }
}
if (import.meta.main) await buildEntryConversations(process.argv[2]);
