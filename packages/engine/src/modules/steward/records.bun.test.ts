test("today buckets: important changes only, latest result, upcoming and decisions", async () => {
  const a = await create("Projection");
  await s.affairs.update(a.id, { care: { cadenceSeconds: 300, notify: "digest" } });
  for (const [kind, important] of [["change", true], ["change", false], ["result", true]] as const) await db.affairEntry.create({ data: { workspaceId: "owner", affairId: a.id, actor: "chrona", kind, text: kind, data: { important }, at: clock } });
  for (const version of [1, 2]) await db.affairResult.create({ data: { workspaceId: "owner", affairId: a.id, version, title: `Result ${version}`, body: "Body", createdAt: clock } });
  await db.followUp.create({ data: { workspaceId: "owner", affairId: a.id, note: "Check", dueAt: new Date(clock.getTime() + 3600000) } });
  const today = c.todayViewSchema.parse(await s.today());
  expect(today.changes.filter(e => e.affairId === a.id)).toHaveLength(1);
  expect(today.results.filter(r => r.affairId === a.id).map(r => r.version)).toEqual([2]);
  expect(today.upcoming.filter(r => r.affairId === a.id)).toHaveLength(2);
  expect(today.decisions.every(a => a.kind !== "suggestion")).toBe(true);
  expect((await s.affairs.getResult(a.id, 1)).version).toBe(1);
  const detail = c.affairDetailSchema.parse(await s.affairs.detail(a.id));
  expect(detail.resultVersions).toHaveLength(2);
  const list = await s.affairs.list();
  expect(list[0]?.openAsks).toBeGreaterThan(0);
});
