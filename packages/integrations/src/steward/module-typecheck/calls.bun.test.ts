test.each(schemas)("JSON Schema rendering: %s", (_name, schema, expected) => {
  expect(tsType(schema)).toBe(expected);
});

test("schema rendering preserves the recursion bound", () => {
  let schema: JsonSchema = { type: "string" };
  for (let depth = 0; depth < 13; depth++) schema = { type: "array", items: schema };
  expect(tsType(schema)).toBe("Array<".repeat(13) + "unknown" + ">".repeat(13));
});

test("calls JSON renders the existing ChronaCalls interface, escaping targets and properties", () => {
  expect(renderCallsDeclaration({
    "app.read": { input: { type: "object", properties: { 'quoted"field': { type: "string" } }, required: ['quoted"field'] }, output: { type: "array", items: { type: "integer" } } },
    "legacy.read": { input: null, output: null },
    'odd"target': { input: false, output: false },
    "opaque.read": { input: true, output: true },
  })).toBe('// Generated by Chrona for this build (v2-25). Do not edit: `chrona.call` takes its argument and result types from here.\nexport interface ChronaCalls {\n'
    + '  "app.read": { args: { "quoted\\"field": string }; output: Array<number> };\n'
    + '  "legacy.read": { args: unknown; output: unknown };\n'
    + '  "odd\\"target": { args: never; output: never };\n'
    + '  "opaque.read": { args: unknown; output: unknown };\n}\n');
  expect(renderCallsDeclaration({})).toContain("export interface ChronaCalls {\n\n}\n");
});

test("writer regenerates declarations and leaves permissions to build helpers", async () => {
  const sdk = await fixture();
  const contracts: CallContracts = { "app.read": { input: null, output: { type: "string" } } };
  const json = JSON.stringify(contracts);
  await writeFile(join(sdk, "calls.json"), json);
  await writeCallsDeclaration(sdk);
  expect(await readFile(join(sdk, "calls.d.ts"), "utf8")).toBe(renderCallsDeclaration(contracts));
  if (process.platform !== "win32") expect((await stat(join(sdk, "calls.d.ts"))).mode & 0o200).toBe(0o200);
  contracts["app.read"]!.output = false;
  await writeFile(join(sdk, "calls.json"), JSON.stringify(contracts));
  await writeCallsDeclaration(sdk);
  expect(await readFile(join(sdk, "calls.d.ts"), "utf8")).toContain("output: never");
  await chmod(join(sdk, "calls.d.ts"), 0o444);
  if (process.platform !== "win32") expect((await stat(join(sdk, "calls.d.ts"))).mode & 0o777).toBe(0o444);
  expect(await readFile(join(sdk, "calls.json"), "utf8")).toBe(JSON.stringify(contracts));
  await chmod(join(sdk, "calls.d.ts"), 0o644);
});

test("calls CLI generates declarations from an SDK path containing spaces", async () => {
  const sdk = await fixture();
  const contracts = { "cli.read": { input: null, output: false } };
  await writeFile(join(sdk, "calls.json"), JSON.stringify(contracts));
  expect(await run("calls.ts", [sdk], sdk)).toEqual({ code: 0, stdout: "", stderr: "" });
  expect(await readFile(join(sdk, "calls.d.ts"), "utf8")).toBe(renderCallsDeclaration(contracts));
});

test("calls CLI reports usage, missing JSON, malformed JSON and write failures as nonzero", async () => {
  const sdk = await fixture();
  const usage = await run("calls.ts", [], sdk);
  expect(usage.code).toBe(2);
  expect(usage.stderr).toContain("Usage: bun --no-install calls.ts <sdkDir>");
  expect((await run("calls.ts", [sdk, "extra"], sdk)).code).toBe(2);
  const missing = await run("calls.ts", [sdk], sdk);
  expect(missing.code).toBe(1);
  expect(missing.stderr).toContain("calls.json");
  await writeFile(join(sdk, "calls.json"), "{");
  const malformed = await run("calls.ts", [sdk], sdk);
  expect(malformed.code).toBe(1);
  expect(malformed.stderr.length).toBeGreaterThan(0);
  await writeFile(join(sdk, "calls.json"), "{}");
  await mkdir(join(sdk, "calls.d.ts"));
  const unwritable = await run("calls.ts", [sdk], sdk);
  expect(unwritable.code).toBe(1);
  expect(unwritable.stderr).toContain("calls.d.ts");
});

test("check generates fresh contracts before checking and preserves diagnostics and guessed-result checks", async () => {
  const directory = await fixture(), sdk = join(directory, "sdk"), module = join(directory, "module");
  await cp(resolve(import.meta.dir, "../module-sdk"), sdk, { recursive: true });
  await mkdir(module);
  await writeFile(join(module, "module.json"), JSON.stringify({ entry: "index.ts" }));
  const contracts: CallContracts = {
    "app.read": { input: { type: "object", properties: { id: { type: "string" } }, required: ["id"] }, output: { type: "object", properties: { value: { type: "string" } }, required: ["value"] } },
    "app.impossible": { input: null, output: false },
    "legacy.read": { input: null, output: null },
    "opaque.read": { input: true, output: true },
  };
  await writeFile(join(sdk, "calls.json"), JSON.stringify(contracts));
  await rm(join(sdk, "calls.d.ts"));
  await writeFile(join(module, "index.ts"), `import { chrona } from "chrona";
const result = await chrona.call("app.read", { id: "x" });
const value: string = result.value;
const impossible: never = await chrona.call("app.impossible");
await chrona.call<{ guessed: true }>("legacy.read");
await chrona.call<{ guessed: true }>("opaque.read");
throw new Error("module code must never execute");
`);
  const good = await run("check.ts", [module, sdk], directory);
  expect(good.stderr).toBe("");
  expect(good.code).toBe(0);
  expect(JSON.parse(good.stdout)).toEqual({ errors: [], total: 0 });
  expect(await readFile(join(sdk, "calls.d.ts"), "utf8")).toBe(renderCallsDeclaration(contracts));

  // A stale declaration must not hide updated calls.json contracts.
  contracts["app.read"]!.output = { type: "object", properties: { value: { type: "integer" } }, required: ["value"] };
  await writeFile(join(sdk, "calls.json"), JSON.stringify(contracts));
  await writeFile(join(module, "index.ts"), `import { chrona } from "chrona";
const result = await chrona.call("app.read", { id: "x" });
const value: string = result.value;
result.missing;
await chrona.call("app.read", { id: 1 });
await chrona.call<{ guessed: true }>("app.read");
await chrona.call<{ guessed: true }>("app.impossible");
await chrona.call<{ guessed: true }>("legacy.read");
`);
  const bad = await run("check.ts", [module, sdk], directory);
  expect(bad.stderr).toBe("");
  expect(bad.code).toBe(1);
  const report = JSON.parse(bad.stdout) as { errors: { file: string; line: number; code: number; message: string }[]; total: number };
  expect(report.errors.map(error => [error.file, error.line, error.code])).toEqual(expect.arrayContaining([
    ["index.ts", 3, 2322], ["index.ts", 4, 2339], ["index.ts", 5, 2769], ["index.ts", 6, 90001], ["index.ts", 7, 90001],
  ]));
  expect(report.errors.filter(error => error.code === 90001).map(error => error.message)).toEqual([
    "app.read has a declared contract: remove the type argument and use the declared result type",
    "app.impossible has a declared contract: remove the type argument and use the declared result type",
  ]);
  expect(report.total).toBe(report.errors.length);
  expect(await readFile(join(sdk, "calls.d.ts"), "utf8")).toBe(renderCallsDeclaration(contracts));
}, 30_000);
