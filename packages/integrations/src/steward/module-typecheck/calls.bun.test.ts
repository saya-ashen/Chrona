import { afterEach, expect, test } from "bun:test";
import { chmod, cp, mkdir, mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { renderCallsDeclaration, tsType, writeCallsDeclaration, type CallContracts, type JsonSchema } from "./calls";

const directories: string[] = [];
afterEach(async () => {
  for (const directory of directories.splice(0)) await rm(directory, { recursive: true, force: true });
});
async function fixture() {
  const directory = await mkdtemp(join(tmpdir(), "chrona calls test "));
  directories.push(directory);
  return directory;
}
async function run(script: string, args: string[], cwd: string) {
  const child = Bun.spawn([process.execPath, "--no-install", join(import.meta.dir, script), ...args], { cwd, stdout: "pipe", stderr: "pipe" });
  const [code, stdout, stderr] = await Promise.all([child.exited, new Response(child.stdout).text(), new Response(child.stderr).text()]);
  return { code, stdout, stderr };
}

