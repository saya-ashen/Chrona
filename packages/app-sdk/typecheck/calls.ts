import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

/** The JSON Schema subset rendered here; other keywords leave the type unknown. */
export type JsonSchema = boolean | {
  type?: string | string[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
  additionalProperties?: JsonSchema;
  items?: JsonSchema;
  enum?: unknown[];
  const?: unknown;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  allOf?: JsonSchema[];
  [keyword: string]: unknown;
};

/** Language-neutral calls.json: null means undeclared or unrepresentable. */
export type CallContracts = Record<string, { input: JsonSchema | null; output: JsonSchema | null }>;

type SchemaObject = Exclude<JsonSchema, boolean>;

function objectType(schema: SchemaObject, depth: number): string {
  const fields = Object.entries(schema.properties ?? {}).map(([key, value]) => `${JSON.stringify(key)}${schema.required?.includes(key) ? "" : "?"}: ${tsType(value, depth + 1)}`);
  const extra = schema.additionalProperties;
  if (extra) fields.push(`[key: string]: ${extra === true ? "unknown" : tsType(extra, depth + 1)}`);
  return `{ ${fields.join("; ")} }`;
}
function compositeType(schema: SchemaObject, depth: number): string | undefined {
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return union.map(part => `(${tsType(part, depth + 1)})`).join(" | ");
  if (schema.allOf) return schema.allOf.map(part => `(${tsType(part, depth + 1)})`).join(" & ");
  if (Array.isArray(schema.type)) return schema.type.map(type => tsType({ ...schema, type }, depth)).join(" | ");
  return undefined;
}
function typedValue(schema: SchemaObject, depth: number): string {
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(" | ") || "never";
  const composite = compositeType(schema, depth);
  if (composite !== undefined) return composite;
  switch (schema.type) {
    case "string": return "string";
    case "number": case "integer": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": return `Array<${tsType(schema.items, depth + 1)}>`;
    case "object": return objectType(schema, depth);
    default: return "unknown";
  }
}
export function tsType(schema: JsonSchema | null | undefined, depth = 0): string {
  if (schema === false) return "never";
  return !schema || schema === true || depth > 12 ? "unknown" : typedValue(schema, depth);
}

/** Render the kernel's plain JSON contracts without depending on kernel implementation types. */
export function renderCallsDeclaration(contracts: CallContracts): string {
  const lines = Object.entries(contracts).map(([target, { input, output }]) =>
    `  ${JSON.stringify(target)}: { args: ${tsType(input)}; output: ${tsType(output)} };`);
  return `// Generated by Chrona for this build (v2-25). Do not edit: \`chrona.call\` takes its argument and result types from here.\nexport interface ChronaCalls {\n${lines.join("\n")}\n}\n`;
}

/** Generate declarations in a writable SDK; callers may make them read-only afterwards. */
export async function writeCallsDeclaration(sdkDir: string): Promise<void> {
  const contracts = JSON.parse(await readFile(join(sdkDir, "calls.json"), "utf8")) as CallContracts;
  await writeFile(join(sdkDir, "calls.d.ts"), renderCallsDeclaration(contracts));
}

if (import.meta.main) {
  const [sdkDir] = process.argv.slice(2);
  if (!sdkDir || process.argv.length !== 3) {
    console.error("Usage: bun --no-install calls.ts <sdkDir>");
    process.exit(2);
  }
  try { await writeCallsDeclaration(sdkDir); }
  catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
